// Rebuilds the essor logo SVGs from geometry measured on the brand sheet.
// Run: node scripts/build-logo.mjs
// Replace with the original vector files from the brand designer when available.
import fs from "node:fs";
import path from "node:path";
import opentype from "opentype.js";

const root = path.resolve(import.meta.dirname, "..");
const r = (n) => Math.round(n * 100) / 100;

// ---- Mark (glyph only, centred on 0,0; outer radius 40) ----
const R = 40; // outer radius
const RI = 26.7; // inner radius
const CUT_X = 14.5; // vertical cut of the top terminal
const ringEndDeg = -23; // radial end of the ring, hidden under the bar
const slope = -0.19; // bar rises to the right
const upperB = -13.97; // y-intercept of bar upper edge
const lowerB = -0.43; // y-intercept of bar lower edge
const barLeftX = -33;

const pt = (rad, deg) => [rad * Math.cos((deg * Math.PI) / 180), rad * Math.sin((deg * Math.PI) / 180)];
const yOut = -Math.sqrt(R * R - CUT_X * CUT_X);
const yIn = -Math.sqrt(RI * RI - CUT_X * CUT_X);
const [oex, oey] = pt(R, ringEndDeg);
const [iex, iey] = pt(RI, ringEndDeg);

// intersection of y = b + slope*x with circle radius R on the right
const hit = (b) => {
  const A = 1 + slope * slope, B = 2 * b * slope, C = b * b - R * R;
  const x = (-B + Math.sqrt(B * B - 4 * A * C)) / (2 * A);
  return [x, b + slope * x];
};
const [ux, uy] = hit(upperB);
const [lx, ly] = hit(lowerB);

const ring = `M${r(CUT_X)} ${r(yOut)}A${R} ${R} 0 1 0 ${r(oex)} ${r(oey)}L${r(iex)} ${r(iey)}A${RI} ${RI} 0 1 1 ${r(CUT_X)} ${r(yIn)}Z`;
// same winding as the ring so nonzero fill unions them
const bar = `M${barLeftX} ${r(lowerB + slope * barLeftX)}L${r(lx)} ${r(ly)}A${R} ${R} 0 0 0 ${r(ux)} ${r(uy)}L${barLeftX} ${r(upperB + slope * barLeftX)}Z`;
const glyph = ring + bar;
const dot = { cx: 31.6, cy: -35.2, r: 8.6 };

// ---- Wordmark "essor" (Poppins SemiBold, x-height scaled to the lockup) ----
const buf = fs.readFileSync(path.join(root, "scripts/Poppins-SemiBold.ttf"));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const glyphH = 80; // mark outer diameter
const xHeightTarget = glyphH / 1.57;
const xHeightUnits = font.tables.os2.sxHeight || 548;
const size = (xHeightTarget / xHeightUnits) * font.unitsPerEm;
const gap = glyphH * 0.27;
const textX = R + gap;
// baseline sits so the x-height is centred a touch above the glyph centre
const baseline = xHeightTarget / 2 - 1.5;
const tracking = 0.012 * size;
let cursor = textX;
let word = "";
let textRight = textX;
for (const ch of "essor") {
  const g = font.charToGlyph(ch);
  const p = g.getPath(cursor, baseline, size);
  word += p.toPathData(2);
  const bb = p.getBoundingBox();
  textRight = Math.max(textRight, bb.x2);
  cursor += (g.advanceWidth / font.unitsPerEm) * size + tracking;
}

const markBox = { x: -41, y: -46, w: 83, h: 87 };
const lockBox = { x: -41, y: -46, w: r(textRight + 42), h: 87 };
const discR = 76.4, discCy = -2.4;

const svg = (box, body, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box.x} ${box.y} ${box.w} ${box.h}" role="img" aria-label="${title}"><title>${title}</title>${body}</svg>\n`;

const coral = "#FF5C5C", navy = "#0F1045", white = "#FFFFFF";
const files = {
  "essor-mark.svg": svg(markBox, `<path fill="${navy}" d="${glyph}"/><circle fill="${coral}" cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/>`, "essor"),
  "essor-mark-white.svg": svg(markBox, `<path fill="${white}" d="${glyph}"/><circle fill="${coral}" cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/>`, "essor"),
  "essor-mark-disc.svg": svg({ x: -discR, y: discCy - discR, w: discR * 2, h: discR * 2 }, `<circle fill="${navy}" cx="0" cy="${discCy}" r="${discR}"/><path fill="${white}" d="${glyph}"/><circle fill="${coral}" cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/>`, "essor"),
  "essor-logo.svg": svg(lockBox, `<path fill="${navy}" d="${glyph}${word}"/><circle fill="${coral}" cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/>`, "essor"),
  "essor-logo-white.svg": svg(lockBox, `<path fill="${white}" d="${glyph}${word}"/><circle fill="${coral}" cx="${dot.cx}" cy="${dot.cy}" r="${dot.r}"/>`, "essor"),
};
for (const [name, content] of Object.entries(files)) fs.writeFileSync(path.join(root, "public/brand", name), content);

const ts = `// Generated by scripts/build-logo.mjs. Do not edit by hand.
export const MARK_PATH = ${JSON.stringify(glyph)};
export const WORD_PATH = ${JSON.stringify(word)};
export const DOT = ${JSON.stringify(dot)};
export const MARK_VIEWBOX = ${JSON.stringify(`${markBox.x} ${markBox.y} ${markBox.w} ${markBox.h}`)};
export const LOGO_VIEWBOX = ${JSON.stringify(`${lockBox.x} ${lockBox.y} ${lockBox.w} ${lockBox.h}`)};
export const DISC = ${JSON.stringify({ r: discR, cy: discCy })};
`;
fs.writeFileSync(path.join(root, "src/components/brand/logo-paths.ts"), ts);
console.log("ok", lockBox);
